#!/usr/bin/env python3
"""Generate rare habitat pools from the actual Red/Blue encounter tables."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def active_lines(text, version):
    active = [True]
    for line in text.splitlines():
        condition = re.match(r"\s*IF DEF\((_RED|_BLUE)\)", line)
        if condition:
            active.append(active[-1] and condition[1] == version)
        elif line.strip() == "ENDC":
            active.pop()
        elif active[-1]:
            yield line.split(";")[0].strip()
    assert len(active) == 1


def habitat_tables(version):
    tables = {}
    for file in (ROOT / "data/wildPokemon").glob("*.asm"):
        lines = list(active_lines(file.read_text(), version))
        label = next(line.split(":")[0] for line in lines if ":" in line)
        rows = [line[3:].strip() for line in lines if line.startswith("db ")]
        habitats = []
        for _ in range(2):
            rate = rows.pop(0)
            if int(rate.replace("$", "0x"), 0) == 0:
                habitats.append([])
            else:
                habitats.append([tuple(row.split(",")) for row in rows[:10]])
                del rows[:10]
        assert not rows, file
        tables[label] = habitats
    return tables


def pools(version):
    maps = re.findall(r"^\s*mapconst\s+(\w+),", (ROOT / "constants/map_constants.asm").read_text(), re.M)
    pointers = re.findall(r"^\s*dw\s+(\w+)", (ROOT / "data/wild_mons.asm").read_text().split("INCLUDE")[0], re.M)
    assert len(maps) == len(pointers)
    source = (ROOT / "data/super_rod.asm").read_text()
    fishing = dict(re.findall(r"dbw\s+(\w+),\s*(\w+)", source))
    groups = {}
    for name, body in re.findall(r"(FishingGroup\d+):([^:]*)(?=FishingGroup\d+:|\Z)", source):
        groups[name] = re.findall(r"db\s+(\d+),\s*(\w+)", body)
    tables = habitat_tables(version)
    rules = json.loads((ROOT / "data/unique_encounter_rules.json").read_text())
    result = []
    for map_name, pointer in zip(maps, pointers):
        land, water = tables[pointer]
        habitats = [land, water, [("10", "GOLDEEN"), ("10", "POLIWAG")], groups.get(fishing.get(map_name), [])]
        for kind, originals in enumerate(habitats):
            # Good Rod works in any fishable water, not just Super Rod groups.
            if kind == 2 and not (water or map_name in fishing):
                continue
            if not originals:
                continue
            variants = []
            for rule in rules:
                if kind not in rule["kinds"]:
                    continue
                if "maps" in rule and map_name not in rule["maps"]:
                    continue
                matches = [pair for pair in originals if pair[1] in rule.get("sources", [])]
                if "sources" in rule and not matches:
                    continue
                level = rule.get("level", int((matches or originals)[0][0]))
                variants.append((level, rule["species"]))
            if variants:
                result.append((map_name, kind, variants))
    return result


def render():
    text = "; Generated by tools/generate_unique_encounters.py; do not edit by hand.\n"
    for version in ("_RED", "_BLUE"):
        rows = pools(version)
        text += f"IF DEF({version})\nUniqueEncounterPools:\n"
        locations = {}
        for map_name, kind, variants in rows:
            text += f"\tdb {map_name}, {kind}, {len(variants)}\n"
            for level, species in variants:
                text += f"\tdb {level}, {species}\n"
                locations.setdefault(species, set()).add(map_name)
        text += "\tdb $ff\n\nUniqueEncounterLocations:\n"
        for species, maps in locations.items():
            text += f"\tdb {species}, {len(maps)}\n\tdb " + ", ".join(sorted(maps)) + "\n"
        text += "\tdb $ff\nENDC\n"
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "data/unique_encounters.asm"
    generated = render()
    if args.check:
        assert path.read_text() == generated, "Regenerate unique encounter pools"
    else:
        path.write_text(generated)
