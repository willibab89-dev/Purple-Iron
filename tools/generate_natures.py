#!/usr/bin/env python3
"""Generate 56 simple and a balanced, reproducible 140-complex nature set."""
from itertools import combinations
from pathlib import Path
import hashlib

ROOT=Path(__file__).resolve().parents[1]
ATTRIBUTES=('HP','ATTACK','DEFENSE','SPEED','SPECIAL','ACCURACY','CRIT','EVASION')

def rotate(mask):return ((mask<<1)&255)|(mask>>7)
def orbit(pair):
    result=set()
    for _ in range(8):
        result.add(pair);pair=tuple(rotate(m) for m in pair)
    return tuple(sorted(result))
def definitions():
    simple=[(1<<up,1<<down) for up in range(8) for down in range(8) if up!=down]
    all_complex={(sum(1<<i for i in up),sum(1<<i for i in down))
                 for up in combinations(range(8),2)
                 for down in combinations([i for i in range(8) if i not in up],2)}
    orbits={orbit(pair) for pair in all_complex}
    def key(o):return hashlib.sha256(b'Purple-Iron nature orbits v1:'+bytes(o[0])).digest()
    selected=sorted((o for o in orbits if len(o)==8),key=key)[:17]
    selected+=sorted((o for o in orbits if len(o)==4),key=key)[:1]
    complex_=[pair for o in selected for pair in o]
    assert len(simple)==56 and len(all_complex)==420 and len(complex_)==140
    assert len(set(simple+complex_))==196
    for up,down in simple+complex_:assert not up&down
    for bit in range(8):
        assert sum(bool(up&(1<<bit)) for up,down in complex_)==35
        assert sum(bool(down&(1<<bit)) for up,down in complex_)==35
    return simple+complex_
def render():
    rows=['; Generated by tools/generate_natures.py. ID = zero-based row.','; Two masks per ID: raised attributes, lowered attributes.','NatureDefinitions::']
    for i,(up,down) in enumerate(definitions()):
        pos='/'.join(a for n,a in enumerate(ATTRIBUTES) if up&(1<<n))
        neg='/'.join(a for n,a in enumerate(ATTRIBUTES) if down&(1<<n))
        rows.append(f'\tdb ${up:02x}, ${down:02x} ; {i}: +{pos}, -{neg}')
    rows+=['NatureDefinitionsEnd:','']
    return '\n'.join(rows)
if __name__=='__main__':
    (ROOT/'data/natures.asm').write_text(render())
    print('196 unique natures: 56 simple, 140 complex; each complex attribute +35/-35')
