#!/usr/bin/env python3
"""Generate seven-stat natures and the old HP multipliers for save migration."""
from itertools import combinations
from pathlib import Path
import hashlib
ROOT=Path(__file__).resolve().parents[1]
ATTRIBUTES=('HP','ATTACK','DEFENSE','SPEED','SPECIAL','ACCURACY','CRIT','EVASION')

def legacy_definitions():
    simple=[(1<<up,1<<down) for up in range(8) for down in range(8) if up!=down]
    def orbit(pair):
        out=set()
        for _ in range(8):
            out.add(pair);pair=tuple(((m<<1)&255)|(m>>7) for m in pair)
        return tuple(sorted(out))
    pairs={(sum(1<<i for i in up),sum(1<<i for i in down)) for up in combinations(range(8),2) for down in combinations([i for i in range(8) if i not in up],2)}
    orbits={orbit(p) for p in pairs}
    key=lambda o: hashlib.sha256(b'Purple-Iron nature orbits v1:'+bytes(o[0])).digest()
    selected=sorted((o for o in orbits if len(o)==8),key=key)[:17]+sorted((o for o in orbits if len(o)==4),key=key)[:1]
    return simple+[pair for o in selected for pair in o]

def definitions():
    old=legacy_definitions(); out=[]
    for i,(up,down) in enumerate(old):
        if i==56: out.append((0,0));continue
        ups=[1<<j for j in range(1,8) if up & (1<<j)]
        downs=[1<<j for j in range(1,8) if down & (1<<j)]
        if not ups: ups=[1<<j for j in range(1,8) if not down & (1<<j)]
        if not downs: downs=[1<<j for j in range(1,8) if not up & (1<<j)]
        out.append((ups[0],downs[0]))
    assert len(out)==196
    assert all((u==d==0) or (u.bit_count()==d.bit_count()==1 and not (u&d) and not ((u|d)&1)) for u,d in out)
    eligible=[i for i in range(7,56) if i%7]+[56]
    assert len(eligible)==43 and len({out[i] for i in eligible})==43
    return out

def render():
    rows=['; Generated by tools/generate_natures.py. ID = zero-based row.','; One raised and one lowered attribute, except neutral ID 56.','NatureDefinitions::']
    for i,(up,down) in enumerate(definitions()):
        pos='/'.join(a for n,a in enumerate(ATTRIBUTES) if up&(1<<n)) or 'NONE'
        neg='/'.join(a for n,a in enumerate(ATTRIBUTES) if down&(1<<n)) or 'NONE'
        rows.append(f'\tdb ${up:02x}, ${down:02x} ; {i}: +{pos}, -{neg}')
    rows+=['NatureDefinitionsEnd:', '', '; Uniform selection from the 42 non-HP pairs and one neutral nature.', 'NatureRollIds::']
    roll_ids=[i for i in range(7,56) if i%7]+[56]
    rows.extend('\tdb '+', '.join(map(str,roll_ids[i:i+14])) for i in range(0,len(roll_ids),14))
    rows+=['NatureRollIdsEnd:', '', '; HP ratios of the previous 196-nature system, for boxed-save migration.', 'NatureLegacyHPRatios::']
    ratios=[110 if u&1 else 90 if d&1 else 100 for u,d in legacy_definitions()]
    rows.extend('\tdb '+', '.join(map(str,ratios[i:i+14])) for i in range(0,len(ratios),14))
    return '\n'.join(rows+['NatureLegacyHPRatiosEnd:',''])
if __name__=='__main__':
    (ROOT/'data/natures.asm').write_text(render())
    print('43 rollable natures: 42 one-up/one-down and one neutral; old IDs preserved')
