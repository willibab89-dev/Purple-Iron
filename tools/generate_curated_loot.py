#!/usr/bin/env python3
"""Explicit supply pools and same-type, comparable-power TM pickup pools."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
LATE_MAPS=['VICTORY_ROAD_1','VICTORY_ROAD_2','VICTORY_ROAD_3','MANSION_1','MANSION_2','MANSION_3','MANSION_4','UNKNOWN_DUNGEON_1','UNKNOWN_DUNGEON_2','UNKNOWN_DUNGEON_3','POWER_PLANT']
PREMIUM=['RARE_CANDY','MAX_ELIXER','MAX_POTION','FULL_RESTORE','PP_UP','MAX_REVIVE']

def pools():
    p={}
    def supply(item,a,b):p[item]=[item]*4+[a]*2+[b]*2
    p['POTION']=['POTION']*3+['ANTIDOTE','PARLYZ_HEAL','AWAKENING','BURN_HEAL','POKE_BALL']
    supply('POKE_BALL','POTION','ANTIDOTE')
    for item,a,b in [('SUPER_POTION','FULL_HEAL','GREAT_BALL'),('HYPER_POTION','FULL_HEAL','ULTRA_BALL'),('MAX_POTION','HYPER_POTION','FULL_RESTORE'),('FULL_RESTORE','MAX_POTION','MAX_REVIVE'),('REVIVE','HYPER_POTION','ULTRA_BALL'),('MAX_REVIVE','FULL_RESTORE','MAX_POTION'),('GREAT_BALL','SUPER_POTION','REVIVE'),('ULTRA_BALL','HYPER_POTION','FULL_HEAL'),('REPEL','ESCAPE_ROPE','SUPER_REPEL'),('SUPER_REPEL','MAX_REPEL','ESCAPE_ROPE'),('MAX_REPEL','SUPER_REPEL','ESCAPE_ROPE'),('ESCAPE_ROPE','REPEL','SUPER_REPEL'),('ETHER','MAX_ETHER','ELIXER'),('MAX_ETHER','ETHER','ELIXER'),('ELIXER','MAX_ETHER','MAX_ELIXER'),('MAX_ELIXER','ELIXER','MAX_ETHER')]:supply(item,a,b)
    cures=['ANTIDOTE','PARLYZ_HEAL','AWAKENING','BURN_HEAL','ICE_HEAL']
    for item in cures:p[item]=[item]*4+[x for x in cures if x!=item]
    vitamins=['HP_UP','PROTEIN','IRON','CARBOS','CALCIUM']
    for item in vitamins:p[item]=[item]*4+[x for x in vitamins if x!=item]
    moves={}
    for line in (ROOT/'data/moves.asm').read_text().splitlines():
        m=re.match(r'\s*move (\w+),\s*(\w+),\s*(\d+),\s*(\w+),\s*(\d+),',line)
        if m:moves[m[1]]=(m[2],int(m[3]),m[4],int(m[5]))
    all_moves=re.findall(r'^\s*db (\w+)',(ROOT/'data/tms.asm').read_text(),re.M)
    tms={f'TM_{i:02}':m for i,m in enumerate(all_moves[:50]+all_moves[55:],1)}
    for item,move in tms.items():
        eff,power,typ,acc=moves[move]
        p[item]=[]
        for candidate,cmove in tms.items():
            ce,cp,ct,ca=moves[cmove]
            # Fixed damage/counters/multi-hit and non-damaging moves retain role.
            if typ!=ct or abs(acc-ca)>25:continue
            if power>1 and cp>1:
                if abs(power-cp)>20:continue
                special={'SELFDESTRUCT','EXPLOSION','HYPER_BEAM','SKULL_BASH','RAGE','RAZOR_WIND','SOLARBEAM'}
                if (move in special or cmove in special) and eff!=ce:continue
                if ('MULTI' in eff or 'TWICE' in eff)!=(('MULTI' in ce or 'TWICE' in ce)):continue
            elif power!=cp or eff!=ce:continue
            p[item].append(candidate)
        assert item in p[item],item
    return p,tms,moves

def render():
    p,_,_=pools()
    out=['; Generated by tools/generate_curated_loot.py; zero IDs terminate lists.','CuratedLateMaps:','\tdb '+', '.join(LATE_MAPS)+', $ff','CuratedPremiumItems:','\tdb '+', '.join(PREMIUM)+', 0','CuratedLootPools:']
    for item in p:out+=['\tdb '+item,'\tdw CuratedPool_'+item]
    out+=['\tdb 0']
    for item,choices in p.items():out+=['CuratedPool_'+item+':','\tdb '+str(len(choices))+', '+', '.join(choices)]
    return '\n'.join(out)+'\n'

def report():
    from collections import Counter
    p,tms,moves=pools()
    out=['# Curated visible loot and new supplies','','Ability Capsules and Nature Capsules cost ¥30,000 each; First Aid costs ¥10,000. All three are sold by the existing post–Elite Four Celadon third-floor vendor. Bag names are ABILITY CAP, NATURE CAP and FIRST AID.','','- Ability Capsule: rerolls a different ability slot, preserving nature. Only species with implemented abilities are eligible (currently the standard Bulbasaur, Charmander and Squirtle families, plus the Caterpie and Weedle evolution lines). Equal odds among the other four slots.','- Nature Capsule: rerolls a different nature, preserving ability slot, DVs, stat experience, moves, PP and status. Recalculates stats and preserves missing HP, with at least 1 HP for a living Pokémon; never revives.','- First Aid: outside battle, heals every living party member by half its own maximum HP, rounded down (minimum 1), capped at maximum. Does not revive or cure status. Consumed only if someone heals.','- All three are consumable, outside-battle items. Cancelled/failed uses consume nothing.','','## Pickup rules','','Visible item balls only. Hidden items, gifts, rewards, shops, HMs, quest items, fossils, evolution stones and other unlisted items retain their original rewards. Each listed pool includes its original item. A location uses a deterministic hash of the saved Trainer ID, map and sprite index, with no game RNG consumed and no new save fields. Leaving, reloading or retrying with a full bag does not reroll. Uncollected items may change if a future patch changes the pools.','','Only premium pickups in the following late areas can yield the new rare items: '+', '.join(LATE_MAPS)+'. Eligible originals: '+', '.join(PREMIUM)+'. For each such pickup: original 10/16, First Aid 4/16, Nature Capsule 1/16, Ability Capsule 1/16. These are per-location probabilities across Trainer IDs; a save need not contain every rare drop. All three have guaranteed postgame shop access.','','TM replacements retain type, damaging/status role and comparable power (within 20) and accuracy (within 25). Status and fixed-damage moves also retain the same effect. Selection uses hash modulo pool size, so non-power-of-two pool weights differ by at most one of 256 hash values. Existing TM compatibility is unchanged.','','## Pools','','| Original | Possible replacements (weights) |','|---|---|']
    for item,choices in p.items():out.append('| '+item+(' ('+tms[item]+')' if item in tms else '')+' | '+', '.join(f'{x} ×{n}' if n>1 else x+(' ('+tms[x]+')' if x in tms else '') for x,n in Counter(choices).items())+' |')
    out+=['','## Visible pickup sites','','| Map | Object | Original | Pool |','|---|---:|---|---|']
    for f in sorted((ROOT/'data/mapObjects').glob('*.asm')):
        header=ROOT/'data/mapHeaders'/f.name
        if not header.exists():continue
        m=re.search(r'\b(\w+)_HEIGHT',header.read_text())
        if not m:continue
        mapname=m[1]
        for line in f.read_text().splitlines():
            m=re.match(r'\s*object SPRITE_BALL,\s*[^,]+,\s*[^,]+,\s*STAY,\s*NONE,\s*(\d+),\s*(\w+)\s*(?:;.*)?$',line)
            if not m:continue
            obj,item=m.groups();pool='Late premium (10/4/1/1)' if mapname in LATE_MAPS and item in PREMIUM else ('Curated' if item in p and len(set(p[item]))>1 else 'Fixed')
            out.append(f'| {mapname} | {obj} | {item} | {pool} |')
    return '\n'.join(out)+'\n'

if __name__=='__main__':
    (ROOT/'data/curated_loot.asm').write_text(render())
    (ROOT/'docs/CURATED-LOOT-AND-SUPPLIES.md').write_text(report())
